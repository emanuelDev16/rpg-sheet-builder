export const TRANSLATION_DICTIONARIES: Record<AppLanguage, TranslationDictionary> = {
  'pt-BR': PT_BR,
  en: EN,
  es: ES,
};

export function translate(
  lang: AppLanguage,
  key: TranslationKey,
  params?: Record<string, string | number>,
): string {
  const dict = TRANSLATION_DICTIONARIES[lang] ?? PT_BR;
  const template = dict[key] ?? PT_BR[key];
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, token: string) =>
    params[token] !== undefined ? String(params[token]) : '',
  );
}

export type TranslateFn = (
  key: TranslationKey,
  params?: Record<string, string | number>,
) => string;

export function createTranslator(lang: AppLanguage): TranslateFn {
  return (key, params) => translate(lang, key, params);
}

